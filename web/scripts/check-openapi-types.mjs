import { mkdtemp, readFile, rm, rmdir, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const schemaUrl = new URL("../contracts/openapi.json", import.meta.url);
const checkedInPath = fileURLToPath(new URL("../src/api/schema.d.ts", import.meta.url));
const temporaryDirectory = await mkdtemp(path.join(os.tmpdir(), "boquitas-openapi-types-"));
const generatedPath = path.join(temporaryDirectory, "schema.d.ts");

function normalizeLineEndings(value) {
  return value.replace(/\r\n?/g, "\n");
}

function diffLines(expectedText, generatedText) {
  const expected = normalizeLineEndings(expectedText).split("\n");
  const generated = normalizeLineEndings(generatedText).split("\n");
  const rows = expected.length + 1;
  const columns = generated.length + 1;
  const common = Array.from({ length: rows }, () => new Uint32Array(columns));

  for (let left = expected.length - 1; left >= 0; left -= 1) {
    for (let right = generated.length - 1; right >= 0; right -= 1) {
      common[left][right] = expected[left] === generated[right]
        ? 1 + (common[left + 1]?.[right + 1] ?? 0)
        : Math.max(common[left + 1]?.[right] ?? 0, common[left]?.[right + 1] ?? 0);
    }
  }

  const output = [];
  let left = 0;
  let right = 0;
  while (left < expected.length || right < generated.length) {
    if (left < expected.length && right < generated.length && expected[left] === generated[right]) {
      output.push(` ${left + 1}/${right + 1} ${expected[left]}`);
      left += 1;
      right += 1;
    } else if (left < expected.length && (right >= generated.length
      || (common[left + 1]?.[right] ?? 0) >= (common[left]?.[right + 1] ?? 0))) {
      output.push(`-${left + 1} ${expected[left]}`);
      left += 1;
    } else {
      output.push(`+${right + 1} ${generated[right]}`);
      right += 1;
    }
  }
  return output;
}

try {
  const generated = `/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n${astToString(await openapiTS(schemaUrl))}`;
  await writeFile(generatedPath, generated, "utf8");
  const checkedIn = await readFile(checkedInPath, "utf8");

  if (normalizeLineEndings(checkedIn) === normalizeLineEndings(generated)) {
    console.log("OpenAPI contract types match src/api/schema.d.ts.");
  } else {
    console.error("Generated OpenAPI types differ from src/api/schema.d.ts. Every diff line follows:");
    console.error("--- src/api/schema.d.ts");
    console.error("+++ generated from contracts/openapi.json");
    for (const line of diffLines(checkedIn, generated)) console.error(line);
    console.error("Run `pnpm contracts:generate` to update the checked-in declaration intentionally.");
    process.exitCode = 1;
  }
} catch (error) {
  console.error("Could not check generated OpenAPI types:", error);
  process.exitCode = 1;
} finally {
  await rm(generatedPath, { force: true });
  await rmdir(temporaryDirectory);
}
