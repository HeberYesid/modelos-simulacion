const page = await context.newPage();
const requests = [];
const external = [];
const errors = [];
page.on('pageerror', error => errors.push(String(error)));
page.on('request', request => {
  const url = new URL(request.url());
  if (url.protocol === 'http:' || url.protocol === 'https:') {
    if (url.origin !== 'http://127.0.0.1:8000') external.push(request.url());
    requests.push(`${request.method()} ${url.pathname}`);
  }
});
await context.route('**/*', route => {
  const url = new URL(route.request().url());
  return /^https?:$/.test(url.protocol) && url.origin !== 'http://127.0.0.1:8000'
    ? route.abort() : route.continue();
});
const postCount = () => requests.filter(line => /^POST \/api\/v1\/(runs|experiments)$/.test(line)).length;
const saved = async payload => {
  await page.getByRole('tab', { name: 'Escenarios', exact: true }).click();
  const response = page.waitForResponse('**/api/v1/files/validate');
  await page.locator('#saved-json-file').setInputFiles({ name: 'acceptance-v2.json', mimeType: 'application/json', buffer: Buffer.from(typeof payload === 'string' ? payload : JSON.stringify(payload)) });
  return response;
};
const download = async (selector, name) => {
  const promise = page.waitForEvent('download');
  await page.locator(selector).click();
  const file = await promise;
  assert.equal(await file.failure(), null);
  const path = resolve(review, name);
  await file.saveAs(path);
  return readFile(path);
};
